/**
 * API Service
 * Handles all HTTP communication with Spring Boot CrudService backend.
 */
const API = {
    /**
     * Internal request wrapper with timeout and error handling.
     */
    async request(endpoint, options = {}, timeoutMs = 8000) {
        const baseUrl = window.CONFIG.getApiBase();
        const url = `${baseUrl}${endpoint}`;

        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), timeoutMs);

        const defaultHeaders = {
            'Content-Type': 'application/json',
            'Accept': 'application/json, text/plain, */*'
        };

        const config = {
            ...options,
            headers: {
                ...defaultHeaders,
                ...options.headers
            },
            signal: controller.signal
        };

        try {
            const response = await fetch(url, config);
            clearTimeout(timeoutId);

            // Parse response body based on content type
            const contentType = response.headers.get('content-type') || '';
            let data;
            if (contentType.includes('application/json')) {
                data = await response.json();
            } else {
                data = await response.text();
            }

            if (!response.ok) {
                // Backend error response
                let errorMessage = `Server error (${response.status}: ${response.statusText})`;
                if (data) {
                    if (typeof data === 'string') {
                        errorMessage = data;
                    } else if (data.message) {
                        errorMessage = data.message;
                    } else if (data.errors && Array.isArray(data.errors)) {
                        errorMessage = data.errors.map(e => e.defaultMessage || e).join(', ');
                    }
                }
                const error = new Error(errorMessage);
                error.status = response.status;
                error.data = data;
                throw error;
            }

            return data;
        } catch (err) {
            clearTimeout(timeoutId);
            if (err.name === 'AbortError') {
                throw new Error('Request timed out. Please check if the backend service is running on port 8081.');
            }
            if (err.message && err.message.includes('Failed to fetch')) {
                throw new Error(`Cannot connect to backend at ${baseUrl}. Ensure Spring Boot CrudService is running.`);
            }
            throw err;
        }
    },

    /**
     * Check backend health / status.
     * GET /gym/
     */
    async checkHealth() {
        return await this.request(window.CONFIG.endpoints.health, { method: 'GET' }, 4000);
    },

    /**
     * Fetch all gym equipment records.
     * GET /gym/Displayall
     */
    async getAll() {
        return await this.request(window.CONFIG.endpoints.displayAll, { method: 'GET' });
    },

    /**
     * Fetch single equipment by ID.
     * GET /gym/Get/{id}
     */
    async getById(id) {
        return await this.request(window.CONFIG.endpoints.getById(id), { method: 'GET' });
    },

    /**
     * Add new gym equipment record.
     * POST /gym/Add
     * Payload: { equipmentname, brand, purchaseCost, working }
     * Note: ID is not included as it is generated by the database/backend.
     */
    async add(recordData) {
        return await this.request(window.CONFIG.endpoints.add, {
            method: 'POST',
            body: JSON.stringify(recordData)
        });
    },

    /**
     * Update existing equipment record.
     * PUT /gym/Update/{id}
     */
    async update(id, recordData) {
        return await this.request(window.CONFIG.endpoints.update(id), {
            method: 'PUT',
            body: JSON.stringify(recordData)
        });
    },

    /**
     * Delete equipment record by ID.
     * DELETE /gym/Delete/{id}
     */
    async delete(id) {
        return await this.request(window.CONFIG.endpoints.delete(id), {
            method: 'DELETE'
        });
    }
};

window.API = API;
